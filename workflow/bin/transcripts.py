#!/usr/bin/env python3
"""Turn the harness's transcripts into Hurl regression suites.

Every FAULTY check on the harness comes with a transcript: the requests of its latest faulty run and what we
answered. All but the last request got an answer the harness accepted; the last is the one it rejected. So each
transcript is a real sequence with known-good steps and one known-bad answer:

  - every step before the failure must keep the status the harness accepted
  - the failing step must not answer what the harness rejected

Ids the harness got back from our responses become Hurl captures; emails get a per-run prefix ({{run}}, set by
check.sh) so a replay doesn't collide with earlier data, while duplicates inside one sequence still collide (the
prefix keeps their letter case).

Reads every feedback snapshot in .local/feedback/ (feedback.sh and watch.sh save them) and writes one suite per
distinct transcript to workflow/hurl/harness/<feature>-<check>-t<tick>.hurl.

Usage: workflow/bin/transcripts.py        (then workflow/bin/check.sh runs them with the other suites)
"""
import glob
import json
import os
import re

OUT = "workflow/hurl/harness"


def rules_since():
    """The tick of the latest claimed change request: a transcript from before it may encode rules that no longer hold
    (submission-cap-cr made co-speaking count, so earlier co-speaker sequences now rightly hit the cap)."""
    try:
        latest = json.load(open(".local/feedback/latest.json"))
    except (OSError, ValueError):
        return 0
    return max([f.get("claimedAtTick") or 0 for f in latest.get("features", [])
                if f.get("slug", "").endswith("-cr") and f.get("claimed")] or [0])


def transcripts():
    since = rules_since()
    seen = {}
    for path in sorted(glob.glob(".local/feedback/*.json")):
        try:
            data = json.load(open(path))
        except (OSError, ValueError):
            continue
        if not isinstance(data, dict):  # timeline files sit in the same folder
            continue
        for feature in data.get("features", []):
            for check in feature.get("checks") or []:
                t = check.get("transcript")
                if t and t.get("requests") and t.get("tick", 0) >= since:
                    seen[(feature["slug"], check["name"], t["tick"])] = t["requests"]
    return seen


def suite(feature, check, tick, requests):
    original = requests
    if requests[-1].get("status") is None:
        # No answer at all: a timeout or a deploy's revision switch, not our behaviour. Keep the steps the harness
        # accepted before it; with none, there's nothing to replay.
        requests = requests[:-1]
        if not requests:
            return None
    ids = {}  # id value from one of our responses -> capture name

    def var(value):
        return "{{" + ids[value] + "}}"

    def path_of(path):
        return "/".join(var(int(p)) if p.isdigit() and int(p) in ids else p for p in path.split("/"))

    def body_of(node, key=None):
        if isinstance(node, dict):
            return {k: body_of(v, k) for k, v in node.items()}
        if isinstance(node, list):
            return [body_of(v) for v in node]
        if isinstance(node, int) and not isinstance(node, bool) and node in ids and key and (key == "id" or key.endswith("Id")):
            return f"__ID_{node}__"
        if isinstance(node, str) and "@" in node:
            return "{{run}}-" + node
        return node

    complete = len(requests) == len(original)  # False when the unanswered last step was dropped
    # Back-to-back writes to the same endpoint are usually one parallel burst (submissions racing for the 3-talk cap,
    # conflicting decisions): which of them wins depends on timing, so the replay can't pin each one's status.
    shape = lambda r: (r["method"], re.sub(r"/\d+", "/{n}", r["path"]))
    burst = {i for i in range(len(requests)) if requests[i]["method"] != "GET" and any(
        0 <= j < len(requests) and shape(requests[j]) == shape(requests[i]) for j in (i - 1, i + 1))}
    lines = [f"# Replay of the harness's {feature}/{check} transcript from tick {tick} (generated by",
             "# workflow/bin/transcripts.py; regenerate rather than edit). Steps before the last kept the status the",
             "# harness accepted; the last is the request it rejected, so it must not answer that again.", ""]
    for n, r in enumerate(requests):
        last = n == len(requests) - 1
        lines.append(f"{r['method']} {{{{base_url}}}}{path_of(r['path'])}")
        if r.get("requestBody"):
            try:
                body = json.dumps(body_of(json.loads(r["requestBody"])), ensure_ascii=False)
                for value, name in ids.items():
                    body = body.replace(f'"__ID_{value}__"', "{{" + name + "}}")
                lines.append(body)
            except ValueError:
                lines.append(r["requestBody"])
        cleanup = r["method"] == "DELETE" and all(q["method"] == "DELETE" for q in requests[:n + 1])
        if cleanup and not (last and complete):
            # The harness's opening clean-up: what it answers depends on the state before (204 or 404), not on us.
            lines += ["HTTP *", "[Asserts]", "status < 500", ""]
            continue
        if n in burst and not (last and complete):
            # no capture: which of the burst wins (and gets an id) isn't fixed
            lines += ["HTTP *", "[Asserts]", "status < 500", ""]
            continue
        if r.get("status") is None:
            # no answer mid-sequence (a timeout under load, often one of several parallel requests): we must answer,
            # not with a 5xx; what exactly depends on which of the parallel requests won
            lines += ["HTTP *", "[Asserts]", "status < 500", ""]
            continue
        if last and complete:  # the step the harness rejected
            lines += ["HTTP *", "[Asserts]", f"status != {r['status']}"]
        else:
            lines.append(f"HTTP {r['status']}")
            try:
                resp = json.loads(r.get("responseBody") or "null")
            except ValueError:
                resp = None
            if isinstance(resp, dict) and isinstance(resp.get("id"), int) and resp["id"] not in ids:
                ids[resp["id"]] = f"id{len(ids) + 1}"
                lines += ["[Captures]", f'{ids[resp["id"]]}: jsonpath "$.id"']
        lines.append("")
    return "\n".join(lines)


def main():
    os.makedirs(OUT, exist_ok=True)
    written, contents = 0, set()
    for (feature, check, tick), requests in sorted(transcripts().items()):
        text = suite(feature, check, tick, requests)
        if text is None:
            continue
        body = text.split("\n", 4)[-1]  # the same sequence seen on several ticks is one suite
        if body in contents:
            continue
        contents.add(body)
        with open(f"{OUT}/{feature}-{check}-t{tick}.hurl", "w") as f:
            f.write(text)
        written += 1
    print(f"{written} harness replays in {OUT}/")


if __name__ == "__main__":
    main()
